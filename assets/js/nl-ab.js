/* ============================================================
   nl-ab.js — распределение игроков по вариантам A/B-тестов.

   Ничего не храним: вариант каждый раз вычисляется заново
   по одному и тому же правилу, поэтому один игрок всегда
   получает один вариант. Ни базы, ни запроса на сервер.
   ============================================================ */

window.NLAB = (function () {
  const CFG = window.NL_CONFIG.experiments || {};

  /* Хэш-функция — «мясорубка» для текста: одинаковый вход даёт
     одинаковое число, похожие входы дают совершенно разные числа.
     FNV-1a + финальное перемешивание.

     Перемешивание в конце обязательно. Без него младший бит FNV-1a —
     это просто XOR младших битов всех символов, и два эксперимента,
     отличающиеся только названием, делят аудиторию одинаково:
     кто попал в вариант A первого теста, гарантированно попадает
     в вариант A второго. Эффекты слипаются и становятся неразделимы.
     Проверено тестом: до правки совпадение вариантов было 0%
     вместо ожидаемых 50%. */
  function hash(str) {
    let h = 2166136261;
    for (let i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    h ^= h >>> 16; h = Math.imul(h, 2246822507);
    h ^= h >>> 13; h = Math.imul(h, 3266489909);
    h ^= h >>> 16;
    return h >>> 0;
  }

  /* Имя эксперимента подмешивается к идентификатору игрока.
     Без этой соли все эксперименты поделят аудиторию одинаково,
     и разделить их эффекты станет невозможно. */
  function variant(name, uid) {
    const exp = CFG[name];
    if (!exp || !exp.enabled) return null;
    return exp.variants[hash(name + ':' + uid) % exp.variants.length];
  }

  /* Все варианты сразу — кладутся в контекст аналитики один раз,
     дальше приезжают с каждым событием автоматически. */
  function assign(uid) {
    const out = {};
    Object.keys(CFG).forEach(function (name) {
      const v = variant(name, uid);
      if (v !== null) out['ab_' + name] = v;
    });
    return out;
  }

  return { variant, assign, hash };
})();
